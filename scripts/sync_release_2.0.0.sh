#!/usr/bin/env bash
# Derive the Autoware 2.0.0 profile's copies from an installed 2.0.0 (the profile's
# launch/autoware-2.0.0.launch.xml; roadmap 077 autopilot axis).
#
# 2.0.0 passes every parameter file as a launch argument down to the launch file that uses it, so
# the 2.0.0 profile includes upstream's own components and sets the files it changes; one copy
# remains:
#
#   components/2.0.0/component_perception.launch.xml: upstream's component_perception with its
#   object recognition (detection, tracking, prediction) under an `object_recognition` argument,
#   default true, as the 1.5.0 profile's perception copy has it (issue 026): false runs the rest --
#   obstacle segmentation, the occupancy grid -- while the vehicle bridge publishes ground-truth
#   objects in recognition's place. The comparison is case-blind: the vehicle bridges pass an
#   $(eval), which yields True/False.
#
#   components/2.0.0/object_recognition_lidar.launch.xml: upstream's (autoware_perception_launch),
#   which the perception copy includes instead: with lidar_detection_model:=clustering (a
#   documented choice, and the profile's default) upstream wires the clustering output as the DNN
#   channel too (detection01 lidar_clustering beside detection03 lidar_clustering), and
#   multi_object_tracker aborts ("parameter 'input_channels.lidar_clustering.flags.
#   can_spawn_new_tracker' has already been declared"). Here detection01 is `none` (no input, as
#   upstream's detection02 without short-range detection) when the model type is clustering.
#
# And the parameter files: scripts/port_config.py --release 2.0.0 (its --check here).
#
#   scripts/sync_release_2.0.0.sh <root>            regenerate (<root>: the 2.0.0 install's
#                                                   /opt/autoware, one directory per package)
#   scripts/sync_release_2.0.0.sh <root> --check    exit 1 if a copy differs from a fresh one
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
root="${1:?usage: sync_release_2.0.0.sh <2.0.0 root (/opt/autoware)> [--check]}"
mode="${2:-}"
share() { if [ -d "$root/$1/share/$1" ]; then echo "$root/$1/share/$1"; else echo "$root/$1"; fi; }
isolated=""; [ -d "$root/autoware_launch/share/autoware_launch" ] && isolated="--isolated"
up="$(share autoware_launch)/launch/components/component_perception.launch.xml"
copy="$here/autoware_sim_profile/launch/components/2.0.0/component_perception.launch.xml"
grp='    <group>'
up_orl="$(share autoware_perception_launch)/launch/object_recognition/object_recognition_lidar.launch.xml"
orl_copy="$here/autoware_sim_profile/launch/components/2.0.0/object_recognition_lidar.launch.xml"
ch01='    <let name="input/detection01/channel" value="lidar_$(var lidar_detection_model_type)"/>'
orl_inc='<include file="$(find-pkg-share autoware_perception_launch)/launch/object_recognition/object_recognition_lidar.launch.xml">'
[ -f "$up_orl" ] || { echo "no upstream object_recognition_lidar at $up_orl"; exit 2; }
[ "$(grep -cxF -- "$ch01" "$up_orl")" = 1 ] || {
    echo "upstream object_recognition_lidar no longer sets detection01's channel as '$ch01'; revisit this copy"; exit 2; }
ns='      <push-ros-namespace namespace="object_recognition"/>'
[ -f "$up" ] || { echo "no upstream component at $up"; exit 2; }
[ "$(grep -cF -- "$orl_inc" "$up")" = 1 ] || {
    echo "upstream component_perception no longer includes object_recognition_lidar exactly once; revisit this copy"; exit 2; }
[ "$(grep -cxF -- "$ns" "$up")" = 1 ] || {
    echo "upstream component_perception no longer pushes the object_recognition namespace exactly once; revisit this copy"; exit 2; }
gen() {
    awk -v grp="$grp" -v ns="$ns" '
        NR == 1 { print; next }
        NR == 2 && $0 == "<launch>" {
            print
            print "  <!-- GENERATED by autoware_sim_vehicle scripts/sync_release_2.0.0.sh from Autoware 2.0.0'"'"'s"
            print "       autoware_launch component_perception.launch.xml; do not edit by hand. Only changes: object"
            print "       recognition runs under the object_recognition argument (issue 026), from the profile'"'"'s"
            print "       object_recognition_lidar copy (clustering as the lidar model). -->"
            print "  <arg name=\"object_recognition\" default=\"true\" description=\"false: no detection, tracking or prediction (ground-truth objects instead)\"/>"
            next
        }
        { lines[++n] = $0 }
        END {
            for (i = 1; i <= n; i++) {
                if (lines[i] == grp && lines[i + 1] == ns)
                    print "    <group if=\"$(eval &quot;'"'"'$(var object_recognition)'"'"'.lower() == '"'"'true'"'"'&quot;)\">"
                else
                    print lines[i]
            }
        }' "$up" | sed "s|$(printf '%s' "$orl_inc" | sed 's/[][\.*^$|]/\\&/g')|<include file=\"\$(find-pkg-share autoware_sim_profile)/launch/components/2.0.0/object_recognition_lidar.launch.xml\">|"
}
gen_orl() {
    awk -v ch01="$ch01" '
        NR == 2 && $0 == "<launch>" {
            print
            print "  <!-- GENERATED by autoware_sim_vehicle scripts/sync_release_2.0.0.sh from Autoware 2.0.0'"'"'s"
            print "       autoware_perception_launch object_recognition_lidar.launch.xml; do not edit by hand. Only"
            print "       change: no detection01 channel when the lidar model is clustering (it is detection03). -->"
            next
        }
        $0 == ch01 {
            print "    <let name=\"input/detection01/channel\" value=\"lidar_$(var lidar_detection_model_type)\" unless=\"$(eval &quot;'"'"'$(var lidar_detection_model_type)'"'"' == '"'"'clustering'"'"'&quot;)\"/>"
            print "    <let name=\"input/detection01/channel\" value=\"none\" if=\"$(eval &quot;'"'"'$(var lidar_detection_model_type)'"'"' == '"'"'clustering'"'"'&quot;)\"/>"
            next
        }
        { print }' "$up_orl"
}
if [ "$mode" = "--check" ]; then
    status=0
    if diff -q <(gen) "$copy" >/dev/null; then echo "2.0.0 perception component copy matches upstream"; else
        echo "2.0.0 perception component copy is out of date with $up; run scripts/sync_release_2.0.0.sh $root"; status=1; fi
    if diff -q <(gen_orl) "$orl_copy" >/dev/null; then echo "2.0.0 object_recognition_lidar copy matches upstream"; else
        echo "2.0.0 object_recognition_lidar copy is out of date with $up_orl; run scripts/sync_release_2.0.0.sh $root"; status=1; fi
    python3 "$here/scripts/port_config.py" --release 2.0.0 --upstream "$root" $isolated --check || status=1
    exit $status
fi
mkdir -p "$(dirname "$copy")"
gen > "$copy"; echo "wrote $copy"
gen_orl > "$orl_copy"; echo "wrote $orl_copy"
python3 "$here/scripts/port_config.py" --release 2.0.0 --upstream "$root" $isolated
