#!/usr/bin/env bash
# Derive autoware_sim_profile's copy of autoware_launch's localization component.
#
# The copy exists for one change (swb roadmap 063 d): the localization error monitor's and the
# EKF's parameter files are arguments, which upstream hard-codes as
# $(var loc_config_path)/<name>.param.yaml. Their defaults are that same path, so at the
# defaults the stack is upstream's (with the profile's loc_config_path, as before). A run
# selects the lane-wide thresholds with them (the profile's
# localization_error_monitor_param_path / ekf_localizer_param_path); the profile's ndt:=none
# uses the same copy with no scan matcher (pose_source none).
#
#   scripts/sync_localization_component.sh          regenerate the copy from the installed upstream
#   scripts/sync_localization_component.sh --check  exit 1 if the copy differs from what it would regenerate
#
# Run --check after an Autoware upgrade; regenerate if it fails.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
share="${AUTOWARE_LAUNCH_SHARE:-/opt/autoware/1.5.0/share/autoware_launch}"
up_component="$share/launch/components/tier4_localization_component.launch.xml"
component="$here/autoware_sim_profile/launch/components/tier4_localization_component.launch.xml"
monitor_value='<arg name="localization_error_monitor_param_path" value="$(var loc_config_path)/localization_error_monitor.param.yaml"/>'
ekf_value='<arg name="ekf_localizer_param_path" value="$(var loc_config_path)/ekf_localizer.param.yaml"/>'
loc_arg='<arg name="loc_config_path" default="$(find-pkg-share autoware_launch)/config/localization"/>'
[ -f "$up_component" ] || { echo "no upstream file $up_component"; exit 2; }
for v in "$monitor_value" "$ekf_value" "$loc_arg"; do
    [ "$(grep -cF "$v" "$up_component")" = 1 ] || {
        echo "upstream no longer has '$v' exactly once; revisit this copy"; exit 2; }
done

esc() { printf '%s' "$1" | sed 's/[][\.*^$|]/\\&/g'; }
gen_component() {
    sed \
        -e "s|$(esc "$monitor_value")|<arg name=\"localization_error_monitor_param_path\" value=\"\$(var error_monitor_param_path)\"/>|" \
        -e "s|$(esc "$ekf_value")|<arg name=\"ekf_localizer_param_path\" value=\"\$(var ekf_param_path)\"/>|" \
        -e "s|$(esc "$loc_arg")|&\n  <!-- GENERATED by autoware_sim_vehicle scripts/sync_localization_component.sh from autoware_launch's\n       tier4_localization_component.launch.xml; do not edit by hand. Only changes:\n       the localization error monitor's and the EKF's parameter files are arguments instead of hard-coded. -->\n  <arg name=\"error_monitor_param_path\" default=\"\$(var loc_config_path)/localization_error_monitor.param.yaml\" description=\"localization error monitor parameter file\"/>\n  <arg name=\"ekf_param_path\" default=\"\$(var loc_config_path)/ekf_localizer.param.yaml\" description=\"EKF localizer parameter file\"/>|" \
        "$up_component"
}

if [ "${1:-}" = "--check" ]; then
    if diff -q <(gen_component) "$component" >/dev/null; then
        echo "localization component copy matches upstream"
    else
        echo "localization component copy is out of date with $up_component"
        echo "run scripts/sync_localization_component.sh"
        exit 1
    fi
else
    gen_component > "$component"; echo "wrote $component"
fi
